import {test} from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {createCommissions} from '../server/commissions.mjs';
import {createFusionQuota} from '../server/fusion-quota.mjs';
test('verified evidence, weekly diary, replay, expiry and atomic rollback',()=>{
 const db=new DatabaseSync(':memory:');db.exec(`PRAGMA foreign_keys=ON;
 CREATE TABLE users(id TEXT PRIMARY KEY);INSERT INTO users VALUES('a'),('b');
 CREATE TABLE card_fusions(user_id TEXT,created_at TEXT);
 CREATE TABLE checkins(user_id TEXT,day TEXT,PRIMARY KEY(user_id,day));
 CREATE TABLE quiz_attempts(user_id TEXT,day TEXT,score INTEGER);
 CREATE TABLE resident_works(id INTEGER PRIMARY KEY,user_id TEXT,status TEXT,updated_at TEXT);
 CREATE TABLE resident_work_reviews(work_id INTEGER,decision TEXT,reviewed_at TEXT);`);
 let stamp='2026-11-08T15:59:59.000Z',auditFails=false;
 const now=()=>stamp,error=(status,message)=>Object.assign(Error(message),{status});
 const tx=fn=>{db.exec('BEGIN IMMEDIATE');try{const r=fn();db.exec('COMMIT');return r}catch(e){db.exec('ROLLBACK');throw e}};
 const audit=()=>{if(auditFails)throw Error('audit failed')};
 const quota=createFusionQuota({db,now,error,audit});
 const service=createCommissions({db,tx,now,error,audit,quota,verify:id=>{if(id!=='a')throw error(403,'未认证')},requireOpen:()=>{}});
 assert.throws(()=>service.claim('b',{taskId:'checkin'}),/未认证/);
 assert.throws(()=>service.claim('a',{taskId:'quiz'}),/完成/);
 assert.throws(()=>service.claim('a',{taskId:'exploration'}),/验证/);
 service.checkin('a');service.claim('a',{taskId:'checkin'});service.claim('a',{taskId:'checkin'});assert.equal(quota.daily('a').taskExtra,1);
 db.prepare('INSERT INTO quiz_attempts VALUES(?,?,?)').run('a','2026-11-08',2);assert.throws(()=>service.claim('a',{taskId:'quiz'}),/完成/);
 db.exec('UPDATE quiz_attempts SET score=3');service.claim('a',{taskId:'quiz'});assert.equal(quota.daily('a').taskExtra,2);
 assert.throws(()=>service.diary('a',{content:'短日记'}),/30/);
 const content='海风吹过灯塔，我和岛民一起记录今天的直播趣事，希望每个回到这里的人都能拥有温柔的回忆。';
 service.diary('a',{content});service.claim('a',{taskId:'diary'});assert.equal(quota.daily('a').taskExtra,3);
 db.exec("INSERT INTO resident_works VALUES(1,'a','submitted','2026-11-08T13:00:00Z');INSERT INTO resident_work_reviews VALUES(1,'approved','2026-11-08T14:00:00Z')");db.exec("UPDATE resident_works SET updated_at='2026-11-08T14:30:00Z'");assert.throws(()=>service.claim('a',{taskId:'creative'}),/完成/);db.exec("UPDATE resident_works SET updated_at='2026-11-08T13:00:00Z'");service.claim('a',{taskId:'creative'});assert.equal(quota.daily('a').taskExtra,5);
 stamp='2026-11-08T16:00:00.000Z';assert.equal(quota.daily('a').limit,3);
 assert.throws(()=>service.diary('a',{content}),/重复/);assert.throws(()=>service.claim('a',{taskId:'creative'}),/完成/);
 auditFails=true;assert.throws(()=>service.checkin('a'),/audit failed/);assert.equal(db.prepare("SELECT count(*) n FROM checkins WHERE day='2026-11-09'").get().n,0);auditFails=false;
 service.checkin('a');service.claim('a',{taskId:'checkin'});assert.equal(quota.daily('a').limit,4);
 const spec={id:'live-support',name:'特别直播应援',description:'提交真实参与说明，由岛主审核',startsAt:'2026-11-01T00:00:00Z',endsAt:'2026-12-01T00:00:00Z',reward:2,limit:'week',requiresReview:true,status:'active',expectedRevision:0,confirmed:true};
 service.configure(spec);assert.throws(()=>service.configure(spec),/更新/);const submission=service.submitSpecial('a',{id:spec.id,content:'我参加了这次直播活动并记录了相关回忆，提交岛主核验。'});
 assert.throws(()=>service.claim('a',{taskId:'special:live-support'}),/审核/);service.reviewSpecial({id:submission.id,decision:'approved',confirmed:true,expectedRevision:1});
 service.claim('a',{taskId:'special:live-support'});service.claim('a',{taskId:'special:live-support'});assert.equal(quota.daily('a').taskExtra,3);
 service.configure({...spec,status:'archived',expectedRevision:1});assert.throws(()=>service.claim('a',{taskId:'special:live-support'}),/开放/);db.close();
});
