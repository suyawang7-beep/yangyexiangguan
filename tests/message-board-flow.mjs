import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {createMessageBoard} from '../server/message-board.mjs';

const db=new DatabaseSync(':memory:');
db.exec("CREATE TABLE users (id TEXT PRIMARY KEY,nickname TEXT NOT NULL); INSERT INTO users VALUES ('BZI-test-user','测试岛民')");
const audits=[];
const tx=fn=>{db.exec('BEGIN');try{const value=fn();db.exec('COMMIT');return value}catch(e){db.exec('ROLLBACK');throw e}};
const board=createMessageBoard(db,(action,details)=>audits.push({action,details}),tx);
const first=board.submit('BZI-test-user',{body:'祝菜菜生日快乐！',anonymous:true});
assert.equal(board.publicRows()[0].author,'匿名岛民');
assert.equal(board.publicRows()[0].body,'祝菜菜生日快乐！');
assert.equal(board.publicRows()[0].userId,undefined);
assert.equal(board.adminRows()[0].hidden,0);
assert.equal(board.adminRows()[0].nickname,'测试岛民');
board.reply({id:first.id,reply:'欢迎登岛！'});
assert.equal(board.publicRows()[0].reply,'欢迎登岛！');
board.moderate({id:first.id,action:'hide'});
assert.equal(board.publicRows().length,0);
assert.equal(board.adminRows()[0].hidden,1);
board.moderate({id:first.id,action:'show'});
assert.equal(board.publicRows().length,1);
board.moderate({id:first.id,action:'delete'});
assert.equal(board.publicRows().length,0);
assert.equal(board.adminRows().length,0);
assert.deepEqual(audits.map(a=>a.action),['message.reply','message.hide','message.show','message.delete']);
assert.throws(()=>board.submit('BZI-test-user',{body:'',anonymous:true}),/留言/);
console.log('Message board isolation, privacy, replies and moderation: OK');
db.close();
